import jsPDF from "jspdf";
import { BrandIdentity, GeneratedSlogan, LogoConfig } from "@/types";

export function generateBrandKitPdf(data: {
  brandName: string;
  industry: string;
  brandIdentity?: BrandIdentity;
  selectedSlogan?: string;
  slogans?: GeneratedSlogan[];
  logoConfig?: LogoConfig;
}) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;

  // Colors
  const primaryColor = data.brandIdentity?.colorPalette[0]?.hex || "#6366F1";
  const darkNeutral = "#0F172A";
  const lightBg = "#F8FAFC";

  // Helper: Hex to RGB
  function hexToRgb(hex: string): [number, number, number] {
    const clean = hex.replace("#", "");
    const bigint = parseInt(clean, 16);
    if (isNaN(bigint)) return [99, 102, 241];
    const r = (bigint >> 16) & 255;
    const g = (bigint >> 8) & 255;
    const b = bigint & 255;
    return [r, g, b];
  }

  const [prR, prG, prB] = hexToRgb(primaryColor);

  // ---------------- PAGE 1: COVER PAGE ----------------
  doc.setFillColor(lightBg);
  doc.rect(0, 0, pageWidth, pageHeight, "F");

  // Top header accent line
  doc.setFillColor(prR, prG, prB);
  doc.rect(0, 0, pageWidth, 8, "F");

  // Modern decorative badge
  doc.setFillColor(prR, prG, prB);
  doc.roundedRect(margin, 35, 45, 8, 3, 3, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.setTextColor(255, 255, 255);
  doc.text("BRAND GUIDELINES", margin + 5, 40.5);

  // Big Brand Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(40);
  doc.setTextColor(15, 23, 42);
  doc.text(data.brandName, margin, 65);

  // Tagline
  const tagline =
    data.brandIdentity?.marketingTagline ||
    data.selectedSlogan ||
    "The modern standard for excellence.";
  doc.setFont("helvetica", "normal");
  doc.setFontSize(14);
  doc.setTextColor(100, 116, 139);
  const splitTagline = doc.splitTextToSize(tagline, contentWidth);
  doc.text(splitTagline, margin, 78);

  // Divider line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(margin, 95, pageWidth - margin, 95);

  // Industry & Date metadata
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139);
  doc.text("INDUSTRY", margin, 110);
  doc.text("VERSION", margin + 60, 110);
  doc.text("GENERATED BY", margin + 120, 110);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text(data.industry || "General Commercial", margin, 118);
  doc.text("1.0 (Official)", margin + 60, 118);
  doc.text("BrandSpark AI Studio", margin + 120, 118);

  // Visual summary card
  doc.setFillColor(255, 255, 255);
  doc.roundedRect(margin, 140, contentWidth, 90, 4, 4, "F");
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, 140, contentWidth, 90, 4, 4, "S");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  doc.text("Brand Essence", margin + 10, 155);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  const missionShort = data.brandIdentity?.mission || "Built to empower modern innovators with unmatched precision and speed.";
  const visionShort = data.brandIdentity?.vision || "To be the defining benchmark of trust and innovation.";
  
  doc.text("MISSION:", margin + 10, 168);
  doc.text(doc.splitTextToSize(missionShort, contentWidth - 20), margin + 10, 174);

  doc.text("VISION:", margin + 10, 195);
  doc.text(doc.splitTextToSize(visionShort, contentWidth - 20), margin + 10, 201);

  // Footer
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text("Confidential — Prepared for internal and stakeholder use.", margin, pageHeight - 15);
  doc.text("Page 1 of 3", pageWidth - margin - 20, pageHeight - 15);

  // ---------------- PAGE 2: BRAND STORY & VALUES ----------------
  doc.addPage();
  doc.setFillColor(lightBg);
  doc.rect(0, 0, pageWidth, pageHeight, "F");

  // Top header accent line
  doc.setFillColor(prR, prG, prB);
  doc.rect(0, 0, pageWidth, 4, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(15, 23, 42);
  doc.text("Brand Story & Core Values", margin, 30);

  // Story paragraph
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  doc.setTextColor(51, 65, 85);
  const storyText =
    data.brandIdentity?.story ||
    `${data.brandName} was founded with a resolute ambition: to reimagine industry standards through relentless craft and user-centric intuition.`;
  const splitStory = doc.splitTextToSize(storyText, contentWidth);
  doc.text(splitStory, margin, 42);

  let currentY = 42 + splitStory.length * 5.2 + 10;

  // Section: Core Values
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text("Foundational Brand Values", margin, currentY);
  currentY += 8;

  const values = data.brandIdentity?.values || [
    { title: "Relentless Craftsmanship", description: "Obsessing over the invisible details to guarantee excellence.", iconName: "Sparkles" },
    { title: "Transparent Trust", description: "Acting with integrity, clear communication, and honesty.", iconName: "Shield" },
    { title: "Velocity with Purpose", description: "Moving with speed to deliver immediate real-world impact.", iconName: "Zap" },
  ];

  values.forEach((val, idx) => {
    if (currentY + 22 > pageHeight - 30) return;
    doc.setFillColor(255, 255, 255);
    doc.roundedRect(margin, currentY, contentWidth, 18, 3, 3, "F");
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(margin, currentY, contentWidth, 18, 3, 3, "S");

    doc.setFillColor(prR, prG, prB);
    doc.circle(margin + 8, currentY + 9, 3, "F");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text(val.title, margin + 16, currentY + 8);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(100, 116, 139);
    doc.text(doc.splitTextToSize(val.description, contentWidth - 30), margin + 16, currentY + 13.5);

    currentY += 22;
  });

  // Footer
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text(`Brand Guidelines — ${data.brandName}`, margin, pageHeight - 15);
  doc.text("Page 2 of 3", pageWidth - margin - 20, pageHeight - 15);

  // ---------------- PAGE 3: PALETTE & TYPOGRAPHY ----------------
  doc.addPage();
  doc.setFillColor(lightBg);
  doc.rect(0, 0, pageWidth, pageHeight, "F");

  doc.setFillColor(prR, prG, prB);
  doc.rect(0, 0, pageWidth, 4, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(15, 23, 42);
  doc.text("Color Palette & Visual System", margin, 30);

  // Swatches
  const palette = data.brandIdentity?.colorPalette || [];
  const swatchWidth = (contentWidth - (palette.length - 1) * 6) / Math.max(1, palette.length);
  let swatchX = margin;

  palette.forEach((color) => {
    const [cR, cG, cB] = hexToRgb(color.hex);
    doc.setFillColor(cR, cG, cB);
    doc.roundedRect(swatchX, 42, swatchWidth, 32, 3, 3, "F");
    doc.setDrawColor(203, 213, 225);
    doc.roundedRect(swatchX, 42, swatchWidth, 32, 3, 3, "S");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(15, 23, 42);
    doc.text(color.hex.toUpperCase(), swatchX, 82);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(color.name, swatchX, 87);
    doc.text(color.role, swatchX, 92);

    swatchX += swatchWidth + 6;
  });

  // Typography Section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text("Typography Direction", margin, 115);

  const typo = data.brandIdentity?.typography;
  const headerFont = typo?.headerFont || "Outfit";
  const bodyFont = typo?.bodyFont || "Inter";

  doc.setFillColor(255, 255, 255);
  doc.roundedRect(margin, 122, contentWidth, 34, 3, 3, "F");
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, 122, contentWidth, 34, 3, 3, "S");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text(`Primary Headline: ${headerFont}`, margin + 10, 133);
  doc.text(`Body Font: ${bodyFont}`, margin + 10, 143);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  const typoExplain = typo?.fontPairingExplanation || "Engineered for maximum optical balance and cross-platform readability.";
  doc.text(doc.splitTextToSize(typoExplain, contentWidth - 20), margin + 10, 150);

  // Social Bios
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text("Official Social Media Profiles", margin, 172);

  const bios = data.brandIdentity?.socialBios || [];
  let bioY = 180;
  bios.forEach((b) => {
    if (bioY + 20 > pageHeight - 30) return;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(prR, prG, prB);
    doc.text(b.platform.toUpperCase(), margin, bioY);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(71, 85, 105);
    const splitBio = doc.splitTextToSize(b.bio, contentWidth);
    doc.text(splitBio, margin, bioY + 5);
    bioY += 6 + splitBio.length * 4.5;
  });

  // Footer
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text(`Brand Guidelines — ${data.brandName}`, margin, pageHeight - 15);
  doc.text("Page 3 of 3", pageWidth - margin - 20, pageHeight - 15);

  // Save the PDF
  const filename = `${data.brandName.toLowerCase().replace(/[^a-z0-9]/g, "-")}-brand-kit.pdf`;
  doc.save(filename);
}

// Download pure SVG file
export function downloadSvgFile(svgContent: string, filename: string) {
  const blob = new Blob([svgContent], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename.endsWith(".svg") ? filename : `${filename}.svg`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

// Export JSON Kit
export function downloadJsonKit(data: Record<string, unknown>, filename: string) {
  const jsonStr = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename.endsWith(".json") ? filename : `${filename}.json`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
